export function scoreCareerMatch(interestProfile = {}, career) {
  const domains = interestProfile?.domains || interestProfile || {};
  const domainEntries = Object.entries(career.domains || {});
  const interestFit = domainEntries.reduce((sum, [domain, weight]) => {
    const score = Number(domains?.[domain]?.score ?? domains?.[domain] ?? 0);
    return sum + score * (weight / 100);
  }, 0);
  const trendFit = Math.max(40, 100 - (career.trendingRank - 1) * 8);
  return Math.min(100, Math.round(interestFit * 0.55 + trendFit * 0.3 + 12));
}

export function scoreCareersForStudent(interestProfile = {}, tier = "intermediate") {
  return CAREER_CATALOG
    .filter((career) => career.tiers.includes(String(tier || "intermediate").toLowerCase()))
    .map((career) => ({
      ...career,
      suitabilityScore: scoreCareerMatch(interestProfile, career),
      reasoning: ["Matched against live interest profile", `${career.marketData.demand} market demand`],
    }))
    .sort((a, b) => b.suitabilityScore - a.suitabilityScore);
}

export function getTrendingCareersForTier(tier = "intermediate") {
  return CAREER_CATALOG
    .filter((career) => career.tiers.includes(String(tier).toLowerCase()))
    .sort((a, b) => a.trendingRank - b.trendingRank)
    .slice(0, 5);
}
